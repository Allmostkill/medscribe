export const PROTOCOL_TEMPLATE_MAX = 4000;
// Контекст из МИС: предыдущий протокол или выписка, которые врач вставил
// перед приёмом. Живёт в одном запросе — нигде не хранится, в промпт входит
// только через wrapUserContent (то есть после деидентификации).
export const PRIOR_CONTEXT_MAX = 6000;
export const capPriorContext = (v: unknown) => (typeof v === 'string' ? v.slice(0, PRIOR_CONTEXT_MAX).trim() : '');

// Потолок длины транскрипта. Проверялся только .trim(), а тело запроса
// допускает 2 МБ — то есть один аккаунт мог 45 раз в минуту отправлять в
// LLM мегабайты текста за счёт владельца ключа. Приём на 60 минут — это
// порядка 40-60 тыс. знаков, так что 120 000 режет только злоупотребление.
export const MAX_TRANSCRIPT_CHARS = 120_000;
export const capTranscript = (t: unknown): string => String(t ?? '').slice(0, MAX_TRANSCRIPT_CHARS);

// Wrap untrusted user content in tags so the model treats it as data, not instructions.
// Defence-in-depth against prompt injection from patient transcripts.
//
// Содержимое экранируется: раньше строка «</transcript>» внутри самих данных
// закрывала ограждение, и всё после неё модель читала как инструкции верхнего
// уровня. Угловые скобки в медицинском тексте встречаются разве что в «< 12
// лет» и «АД > 140», поэтому замена на «‹ ›» ничего осмысленного не портит.
//
// Здесь же — единственная дверь В промпт для текста пациента, и потому
// здесь же он деидентифицируется: имена, телефоны, даты, номера документов
// заменяются метками до того, как строка попадёт в промпт.
export function wrapUserContent(label: string, content: string): string {
  const hidden = deidContext.getStore()?.hide(String(content ?? '')) ?? String(content ?? '');
  const safe = hidden.replace(/</g, '‹').replace(/>/g, '›');
  return `<${label}>\n${safe}\n</${label}>`;
}

// Значение, подставляемое в промпт ВНЕ ограждения (специальность, заголовок
// шаблона): переводы строк и скобки убираем, длину режем — иначе поле уровня
// инструкций позволяет переписать системный промпт целиком.
export function sanitizePromptField(value: unknown, max = 120): string {
  return String(value ?? '')
    .replace(/[\r\n\u2028\u2029\v\f\x85<>]/g, ' ')
    .slice(0, max)
    .trim();
}
