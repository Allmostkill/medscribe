/**
 * Деидентификация текста перед отправкой в языковую модель.
 *
 * Стенограмма и протокол уходят в языковую модель (LLM-провайдер из .env). Протоколу
 * имя пациента не нужно: модель одинаково хорошо соберёт анамнез для
 * «Марины Сергеевны» и для «[ИМЯ 1]». Поэтому имена, отчества, фамилии,
 * телефоны, полные даты, номера документов и почта заменяются метками ДО
 * промпта и возвращаются на место ПОСЛЕ ответа модели. Врач видит настоящие
 * имена; модель — нет.
 *
 * Как устроено:
 * - Одна метка на одну сущность в одной форме: «Марина» → [ИМЯ 1.1],
 *   «Марину» → [ИМЯ 1.2]. Первый номер общий для всех форм одного имени,
 *   чтобы модель видела одного человека; второй различает формы, чтобы
 *   восстановление было точным до буквы — цитаты сверки протокола обязаны
 *   совпадать со стенограммой дословно.
 * - Восстановление терпимо к тому, как модель переписывает метку: регистр,
 *   пробелы, потерянный второй номер.
 * - Ложное срабатывание дешевле пропуска: слово, принятое за фамилию,
 *   вернётся на место после ответа; имя, принятое за слово, уедет за границу.
 *   Отсюда широкие правила и словарь без оглядки на редкие омонимы —
 *   кроме тех, что встречаются в речи постоянно (вера, надежда, роман…):
 *   для них нужна заглавная буква.
 *
 * Чего здесь НЕТ (и это надо помнить): адресов и названий населённых пунктов,
 * мест работы, редких имён вне словаря, произнесённых цифрами телефонов
 * («восемь девятьсот…»).
 */
