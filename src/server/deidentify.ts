// Имена-омонимы: в речи это чаще слово, чем имя. Скрываются только с заглавной.
const HOMONYMS = `Вера Надежда Любовь Роман Лев Света Лена Роза Лилия Мила Марта Ника Слава Майя Мира Тома Лука Марк Рада Лада Ася Тая Влада Дана Инна Алла Соня Поля Гуля Ната Софа Аля Гена Костя Тема Тёма Лёня Леня Стёпа Степа`;
const HOMONYM_SET = new Set(HOMONYMS.split(/\s+/).map(norm));

/** Формы имени по простым правилам склонения. */
function forms(name: string): string[] {
  const n = norm(name);
  const last = n[n.length - 1];
  const vowels = 'аеиоуыэюя';
  if (last === 'а' || last === 'я') {
    const stem = n.slice(0, -1);
    return ['а', 'я', 'ы', 'и', 'е', 'у', 'ю', 'ой', 'ей', 'ою', 'ею'].map(e => stem + e);
  }
  if (last === 'ь' || last === 'й') {
    const stem = n.slice(0, -1);
    return [last, 'я', 'ю', 'ем', 'е', 'и'].map(e => stem + e);
  }
  if (vowels.includes(last)) return [n];
  return ['', 'а', 'у', 'ом', 'е', 'я', 'ю', 'ем'].map(e => n + e);
}

const L = '(?<![\\p{L}\\p{N}])';
const R = '(?![\\p{L}\\p{N}])';
const alt = (names: string, lower: boolean) => [...new Set(names.split(/\s+/).filter(Boolean)
  // Омонимы из общего списка убираются: там они скрывались бы и строчными.
  .filter(n => !lower || !HOMONYM_SET.has(norm(n)))
  .flatMap(forms).map(f => (lower ? f.toLowerCase() : f)))]
  .sort((a, b) => b.length - a.length).join('|');

// Словарные имена — без учёта регистра: T-one отдаёт текст строчными.
const FIRST_NAMES = new RegExp(`${L}(?:${alt(MALE + ' ' + FEMALE, true)})${R}`, 'giu');
// Омонимы — только с заглавной, как написано.
const HOMONYM_NAMES = new RegExp(`${L}(?:${alt(HOMONYMS, false)})${R}`, 'gu');
// Отчества: суффикс однозначен и в любом регистре.
const PATRONYMICS = new RegExp(`${L}\\p{L}{2,}(?:(?:ович|евич|ьич|мич|тич|кич)(?:а|у|ем|е)?|(?:овн|евн|ичн|иничн)(?:а|ы|е|у|ой))${R}`, 'giu');
// Фамилии: только с заглавной — суффиксы слишком общие для строчных слов.
const SURNAMES = new RegExp(`${L}[\\p{Lu}]\\p{Ll}{2,}(?:ов|ев|ёв|ин|ын|ова|ева|ёва|ина|ына|ову|еву|ину|овым|евым|иным|ове|еве|ине|ский|цкий|ская|цкая|ского|цкого|скому|цкому|ским|цким|ской|цкой|их|ых|енко|чук|юк|ян|яна|яну|швили|дзе|оглы|заде)${R}`, 'gu');
const PHONES = /(?:\+7|8)[\s(-]*\d{3}[\s)-]*\d{3}[\s-]*\d{2}[\s-]*\d{2}/g;
const EMAILS = /[\w.+-]+@[\w-]+\.[\w.-]+/g;
const DATES = /(?<!\d)\d{1,2}[./]\d{1,2}[./](?:19|20)\d{2}(?!\d)|(?<![\p{L}\p{N}])\d{1,2}\s+(?:января|февраля|марта|апреля|мая|июня|июля|августа|сентября|октября|ноября|декабря)\s+(?:19|20)\d{2}(?:\s*г(?:ода|\.)?)?(?![\p{L}\p{N}])/gu;
// СНИЛС, полис ОМС (16 цифр), паспорт (4+6), любые длинные номера.
const NUMBERS = /\d{3}-\d{3}-\d{3}[- ]\d{2}|(?<!\d)\d{4}\s?\d{6}(?!\d)|(?<!\d)\d{10,}(?!\d)/g;
// Фамилия строчными — по соседству с уже найденным именем или отчеством:
// «марина сергеевна петрова». T-one отдаёт строчные, и без этого правила
// фамилия из стенограммы уезжала бы в модель нетронутой.
const ADJ_SUFFIX = '(?:ов|ев|ёв|ова|ева|ёва|ову|еву|овой|евой|ин|ина|ину|иной|ын|ына|ский|ская|цкий|цкая|ского|ской|енко|чук|юк|швили|дзе|ян|оглы|заде|их|ых)';
const ADJ_STOP = new Set(['снова', 'готов', 'готова', 'здоров', 'здорова', 'нездоров', 'один', 'витамин', 'аспирин', 'инсулин', 'анальгин', 'магазин', 'причин', 'мужчин', 'женщин', 'больных', 'других', 'своих', 'этих', 'таких', 'многих', 'их']);
const ADJ_AFTER = new RegExp(`(\\u0000ИМЯ\\|\\d+\\u0000)([ ,]+)(\\p{L}{3,}${ADJ_SUFFIX})${R}`, 'giu');
const ADJ_ALONE = new RegExp(`${L}(\\p{L}{4,}${ADJ_SUFFIX})${R}`, 'giu');
const ADJ_BEFORE = new RegExp(`${L}(\\p{L}{3,}${ADJ_SUFFIX})([ ,]+)(\\u0000ИМЯ\\|\\d+\\u0000)`, 'giu');

type Kind = 'ИМЯ' | 'ТЕЛЕФОН' | 'ДАТА' | 'НОМЕР' | 'ПОЧТА';

export interface Deidentifier {
  hide(text: string): string;
  restore(text: string): string;
  readonly stats: Record<Kind, number>;
}

export function createDeidentifier(): Deidentifier {
  // base → { index, forms: surface[] }; номера выдаются в порядке появления
  // в тексте, а не в порядке правил — так «[ИМЯ 1]» для модели и для
  // человека, читающего лог, это первый названный человек.
  const bases = new Map<string, { index: number; forms: string[] }>();
  const counters: Record<Kind, number> = { 'ИМЯ': 0, 'ТЕЛЕФОН': 0, 'ДАТА': 0, 'НОМЕР': 0, 'ПОЧТА': 0 };
  const stats: Record<Kind, number> = { 'ИМЯ': 0, 'ТЕЛЕФОН': 0, 'ДАТА': 0, 'НОМЕР': 0, 'ПОЧТА': 0 };

  // Пока идут правила, находка заменяется непрозрачным токеном
  // \u0000KIND|n\u0000, а сам текст находки лежит в боковой таблице. Токен
  // не содержит ни букв, ни длинных чисел — следующим правилам в нём нечего
  // ловить. Прозрачный токен с текстом внутри уже подводил: десять цифр
  // телефона внутри метки ловились правилом номеров, и метка ломалась.
  // Нумерация — одним проходом в конце.
  const found: { kind: Kind; baseKey: string; surface: string }[] = [];
  const token = (kind: Kind, surface: string, baseKey: string) => {
    found.push({ kind, baseKey, surface });
    return `\u0000${kind}|${found.length - 1}\u0000`;
  };
  const number = (kind: Kind, baseKey: string, surface: string) => {
    const key = `${kind}:${baseKey}`;
    let entry = bases.get(key);
    if (!entry) { entry = { index: ++counters[kind], forms: [] }; bases.set(key, entry); }
    let formIdx = entry.forms.indexOf(surface);
    if (formIdx < 0) { entry.forms.push(surface); formIdx = entry.forms.length - 1; }
    stats[kind]++;
    return `[${kind} ${entry.index}.${formIdx + 1}]`;
  };
  // Одно имя в разных падежах и регистрах — одна сущность: ключ по началу слова.
  const nameKey = (s: string) => norm(s).toLowerCase().slice(0, 5);
  const sub = (text: string, re: RegExp, kind: Kind, keyOf: (s: string) => string) =>
    text.replace(re, m => token(kind, m, keyOf(m)));

  return {
    stats,
    hide(text) {
      let t = String(text ?? '');
      t = sub(t, EMAILS, 'ПОЧТА', s => s.toLowerCase());
      t = sub(t, PHONES, 'ТЕЛЕФОН', s => s.replace(/\D/g, '').slice(-10));
      t = sub(t, NUMBERS, 'НОМЕР', s => s.replace(/\D/g, ''));
      t = sub(t, DATES, 'ДАТА', s => s.replace(/\s+/g, ' '));
      t = sub(t, PATRONYMICS, 'ИМЯ', nameKey);
      t = sub(t, SURNAMES, 'ИМЯ', nameKey);
      t = sub(t, HOMONYM_NAMES, 'ИМЯ', nameKey);
      t = sub(t, FIRST_NAMES, 'ИМЯ', nameKey);
      const adj = (word: string) => !ADJ_STOP.has(norm(word).toLowerCase());
      t = t.replace(ADJ_AFTER, (m, tok, gap, word) => adj(word) ? `${tok}${gap}${token('ИМЯ', word, nameKey(word))}` : m);
      t = t.replace(ADJ_BEFORE, (m, word, gap, tok) => adj(word) ? `${token('ИМЯ', word, nameKey(word))}${gap}${tok}` : m);
      // Фамилия, найденная по соседству с именем, скрывается и там, где стоит
      // одна: «сын гаджиева» после «гаджиев магомед расулович».
      const knownKeys = new Set(found.filter(f => f.kind === 'ИМЯ').map(f => f.baseKey));
      t = t.replace(ADJ_ALONE, (m, word) => knownKeys.has(nameKey(word)) && adj(word) ? token('ИМЯ', word, nameKey(word)) : m);
      return t.replace(/\u0000(?:ИМЯ|ТЕЛЕФОН|ДАТА|НОМЕР|ПОЧТА)\|(\d+)\u0000/g,
        (_, n: string) => { const f = found[Number(n)]; return number(f.kind, f.baseKey, f.surface); });
    },
    restore(text) {
      const byIndex = new Map<string, { forms: string[] }>();
      for (const [key, entry] of bases) byIndex.set(`${key.split(':')[0]}:${entry.index}`, entry);
      return String(text ?? '').replace(
        /\[\s*(ИМЯ|ТЕЛЕФОН|ДАТА|НОМЕР|ПОЧТА)\s*(\d+)(?:\s*[.,]\s*(\d+))?\s*\]/giu,
        (m, kind: string, idx: string, form?: string) => {
          const entry = byIndex.get(`${kind.toUpperCase()}:${idx}`);
          if (!entry) return m;
          return entry.forms[form ? Number(form) - 1 : 0] ?? entry.forms[0];
        });
    },
  };
}

/**
 * Контекст запроса: один деидентификатор на HTTP-запрос. Ограждение
 * (wrapUserContent) скрывает через него, вызов модели (llmGenerate)
 * восстанавливает. Ни один обработчик не может «забыть» деидентификацию —
 * двери в промпт и из модели одни на всех.
 */
export const deidContext = new AsyncLocalStorage<Deidentifier>();
