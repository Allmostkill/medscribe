// Primary visit ("первичный приём") follows the Ministry of Health structure:
// complaints → anamnesis morbi → anamnesis vitae → allergies → epidemiology →
// examination → preliminary diagnosis → plan. Keywords are stems (Russian morphology
// varies a lot) and intentionally generous — we'd rather false-positive a checkmark
// than constantly nag the doctor about items they already covered.
//
// Вынесено из Dashboard.tsx в отдельный модуль — переиспользуется и ChecklistPanel,
// и TranscriptBlock (мобильный чип прогресса чек-листа), без циклического импорта
// из Dashboard.tsx.

// Union перечисляет все идентификаторы, реально встречающиеся ниже. Раньше
// он описывал только восемь базовых, и специальные пункты специальностей
// (ecg, risk_factors, meds_tolerance…) давали 86 ошибок TS2345 — ровно
// столько же ложных строк в выводе tsc, за которыми переставали быть видны
// настоящие ошибки типов. Сами пункты работали: id используется только как
// React key в ChecklistPanel, и дублей внутри списков нет.
