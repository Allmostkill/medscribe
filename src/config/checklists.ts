/**
 * Returns the right pair of checklists for a given specialty id.
 * Falls back to the general Минздрав template for unknown specialties.
 */
export function getSpecialtyChecklists(specialtyId?: string): { primary: ChecklistItem[]; followUp: ChecklistItem[] } {
  switch (specialtyId) {
    case 'psychiatrist':     return { primary: PSYCHIATRIC_PRIMARY_CHECKLIST, followUp: PSYCHIATRIC_FOLLOW_UP_CHECKLIST };
    case 'cardiologist':     return { primary: CARDIO_PRIMARY, followUp: CARDIO_FOLLOW_UP };
    case 'endocrinologist':  return { primary: ENDO_PRIMARY, followUp: ENDO_FOLLOW_UP };
    case 'neurologist':      return { primary: NEURO_PRIMARY, followUp: NEURO_FOLLOW_UP };
    case 'pediatrician':     return { primary: PEDIATRIC_PRIMARY, followUp: PEDIATRIC_FOLLOW_UP };
    case 'pulmonologist':    return { primary: PULM_PRIMARY, followUp: PULM_FOLLOW_UP };
    case 'gynecologist':     return { primary: GYNEC_PRIMARY, followUp: GYNEC_FOLLOW_UP };
    case 'gastroenterologist': return { primary: GASTRO_PRIMARY, followUp: GASTRO_FOLLOW_UP };
    case 'dermatologist':    return { primary: DERM_PRIMARY, followUp: DERM_FOLLOW_UP };
    case 'ophthalmologist':  return { primary: OPHTH_PRIMARY, followUp: OPHTH_FOLLOW_UP };
    case 'otolaryngologist': return { primary: ENT_PRIMARY, followUp: ENT_FOLLOW_UP };
    case 'urologist':        return { primary: UROL_PRIMARY, followUp: UROL_FOLLOW_UP };
    case 'orthopedist':      return { primary: ORTHO_PRIMARY, followUp: ORTHO_FOLLOW_UP };
    case 'ultrasound':       return { primary: ULTRASOUND_PRIMARY, followUp: ULTRASOUND_FOLLOW_UP };
    case 'dentist':          return { primary: DENTIST_PRIMARY, followUp: DENTIST_FOLLOW_UP };
    default:                 return { primary: PRIMARY_CHECKLIST, followUp: FOLLOW_UP_CHECKLIST };
  }
}

