export function getDrugClassKey(group?: string, mnn?: string): string | undefined {
  const byMnn = mnn ? DRUG_CLASS_BY_MNN[mnn.trim().toLowerCase()] : undefined;
  if (byMnn && DRUG_CLASS_INFO[byMnn]) return byMnn;
  return group && DRUG_CLASS_INFO[group] ? group : undefined;
}
