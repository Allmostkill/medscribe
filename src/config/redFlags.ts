/**
 * Красные флаги под набор клинических категорий диагноза. Категории приходят
 * из Icd10Code.category (см. findIcd10Categories в icd10Reference.ts).
 *
 * Наборы нескольких категорий объединяются с сохранением порядка и без
 * дублей: у пациента бывает больше одного диагноза, и потерять флаг из-за
 * того, что он «не первый», нельзя. Если ни одна категория не распознана —
 * возвращаем общий набор: пустой раздел «когда срочно» хуже, чем общий.
 */
export function getRedFlags(categories: string[]): RedFlagSet {
  const sets = categories
    .map(c => RED_FLAGS_BY_CATEGORY[c])
    .filter((s): s is RedFlagSet => !!s);

  if (sets.length === 0) return RED_FLAGS_GENERIC;

  const dedupe = (lists: string[][]) => [...new Set(lists.flat())];
  return {
    emergency: dedupe(sets.map(s => s.emergency)),
    urgent: dedupe(sets.map(s => s.urgent)),
  };
}
