// Красные флаги для памятки пациенту: «когда обращаться срочно».
//
// Почему это КУРИРУЕМЫЙ справочник, а не генерация моделью. Раздел «когда
// срочно к врачу» — единственная часть памятки, где ошибка стоит жизни, и при
// этом самая предсказуемая: тревожные симптомы при гипертензии одинаковы для
// всех пациентов с гипертензией, вариативность тут не нужна и вредна. Модель
// использует эти формулировки как есть, ей остаётся только не потерять их при
// сборке текста (см. /api/ai/patient-summary).
//
// Ключ — Icd10Code.category из icd10Reference.ts, тот же, по которому уже
// связаны шаблоны назначений и фарм-справочник.
//
// Это НЕ клиническая рекомендация и не замена решению врача: набор
// намеренно короткий и консервативный, врач правит памятку перед выдачей.

