/**
 * Проверка отбора пунктов разбора общения.
 *
 *   tsx scripts/check-communication.ts
 *
 * Слой подсказывает врачу, как он мог сказать иначе, и цитирует его же
 * реплику. Цитата — единственное, что делает подсказку проверяемой, и она же
 * самый вероятный способ соврать: «вы сказали X» звучит одинаково убедительно
 * и когда X было сказано, и когда не было. Модель, которую попросили
 * цитировать, регулярно цитирует «по смыслу» — своими словами.
 *
 * Поэтому сервер сверяет каждую цитату со стенограммой и выбрасывает пункт,
 * которому нет подтверждения. Здесь проверяется НАСТОЯЩИЙ код этого отбора
 * (src/server/ai/validate.ts), а не переписанная копия, на типовых выдумках модели.
 */
import { validateCommunicationNotes as validate } from '../src/server/ai/validate';

const transcript = [
  'Врач: Здравствуйте, что вас беспокоит?',
  'Пациент: Болит живот уже вторую неделю. А это не рак?',
  'Врач: Вы неправильно принимаете таблетки, я же говорил.',
  'Пациент: Я старалась, просто забывала иногда.',
  'Врач: Ну это же очевидно, надо было по расписанию.',
  'Врач: Придётся удалить желудок.',
].join('\n');

const good = {
  kind: 'phrasing', speaker: 'doctor',
  quote: 'Вы неправильно принимаете таблетки',
  alternative: 'Давайте сверим, как вы их принимаете — где сбивается?',
  why: 'Убирает обвинение и оставляет пациенту возможность рассказать правду.',
  protocol: 'МИ',
};

const cases: [string, any, boolean][] = [
  ['цитата дословно',            good, true],
  ['цитата в другом регистре',   { ...good, quote: 'ВЫ НЕПРАВИЛЬНО ПРИНИМАЕТЕ ТАБЛЕТКИ' }, true],
  ['цитата с другой пунктуацией',{ ...good, quote: 'вы неправильно принимаете таблетки,' }, true],
  ['пропуск: реплика пациента',  { kind: 'gap', speaker: 'patient', quote: 'А это не рак?', why: 'Вопрос остался без ответа.', protocol: 'ask-tell-ask' }, true],
  ['[выброс] выдуманная цитата', { ...good, quote: 'Вы совершенно безответственно относитесь к лечению' }, false],
  ['[выброс] пересказ по смыслу',{ ...good, quote: 'врач упрекнул пациентку в несоблюдении режима' }, false],
  ['[выброс] формулировка без альтернативы', { ...good, alternative: '' }, false],
  ['[выброс] без объяснения',    { ...good, why: '' }, false],
  ['[выброс] пустая цитата',     { ...good, quote: '' }, false],
  ['[выброс] не объект',         'просто строка', false],
];

let bad = 0;
for (const [name, note, want] of cases) {
  const { notes } = validate([note], transcript);
  const kept = notes.length === 1;
  if (kept !== want) bad++;
  console.log(`  ${kept === want ? '✓' : '✗'} ${name.padEnd(42)} ${kept ? 'принято' : 'отброшено'}`);
}

// Протокол, которого нет в списке, не должен доезжать до врача как есть.
const { notes: n1 } = validate([{ ...good, protocol: 'ВЫДУМАННЫЙ ПРОТОКОЛ' }], transcript);
const protoOk = n1[0]?.protocol === 'общее';
console.log(`  ${protoOk ? '✓' : '✗'} ${'неизвестный протокол → «общее»'.padEnd(42)} ${n1[0]?.protocol}`);
if (!protoOk) bad++;

// Потолок на число пунктов: разбор не должен превращаться в разнос.
const { notes: n2 } = validate(Array.from({ length: 12 }, () => ({ ...good })), transcript);
const capOk = n2.length === 5;
console.log(`  ${capOk ? '✓' : '✗'} ${'не больше пяти пунктов'.padEnd(42)} ${n2.length}`);
if (!capOk) bad++;

console.log(bad ? `\nНЕСОВПАДЕНИЙ: ${bad}` : '\nотбор пунктов работает как задумано');
process.exit(bad ? 1 : 0);
